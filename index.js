export function chunkText(text, max = 3800) {
if (text.length <= max) return [text];
const out = [];
let cur = "";
for (const line of text.split("\n")) {
if ((cur + "\n" + line).length > max) { if (cur) out.push(cur); cur = line.slice(0, max); }
else cur = cur ? cur + "\n" + line : line;
}
if (cur) out.push(cur);
return out;
}
