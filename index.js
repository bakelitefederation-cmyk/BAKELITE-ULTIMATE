const SHORTENERS = new Set(["bit.ly", "t.co", "tinyurl.com", "cutt.ly", "is.gd", "goo.gl", "ow.ly", "rebrand.ly", "clck.ru", "vk.cc", "tiny.cc", "shorturl.at"]);
const SUSP_TLD = new Set(["zip", "mov", "top", "xyz", "click", "link", "gq", "tk", "ml", "ga", "cf", "work", "rest", "country", "loan", "icu", "monster", "buzz", "cfd", "sbs"]);
const BRANDS = ["paypal", "google", "facebook", "instagram", "telegram", "whatsapp", "apple", "microsoft", "amazon", "netflix", "binance", "coinbase", "metamask", "privatbank", "monobank", "novaposhta", "ukrposhta", "kyivstar", "vodafone", "olx", "diia", "steam", "discord"];
const WORDS = ["login", "signin", "verify", "secure", "account", "update", "wallet", "airdrop", "bonus", "gift", "prize", "claim", "confirm", "recovery", "support", "refund", "payment"];
const MULTI = new Set(["co.uk", "com.ua", "org.ua", "net.ua", "kiev.ua", "in.ua", "com.br", "co.jp", "com.au", "co.in"]);

export function registrable(host) {
  const l = host.split(".");
  const two = l.slice(-2).join(".");
  return MULTI.has(two) && l.length >= 3 ? l.slice(-3).join(".") : two;
}
const look = (s) => s.replace(/0/g, "o").replace(/1/g, "l").replace(/3/g, "e").replace(/5/g, "s").replace(/rn/g, "m").replace(/vv/g, "w");
function lev(a, b) {
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++)
    d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return d[a.length][b.length];
}

export function heuristics(rawUrl) {
  const reasons = [];
  let score = 0;
  const add = (pts, why) => { score += pts; reasons.push(why); };
  let u;
  try { u = new URL(rawUrl); } catch { return { ok: false, score: 0, reasons: ["Не удалось разобрать ссылку"] }; }
  if (u.protocol !== "http:" && u.protocol !== "https:") return { ok: false, score: 0, reasons: ["Это не веб-ссылка"] };

  const host = u.hostname.toLowerCase();
  const reg = registrable(host);
  const sld = reg.split(".")[0];
  const labels = host.split(".");
  const tld = labels[labels.length - 1];

  if (net.isIP(host) || /^\[.*\]$/.test(host)) add(3, "вместо названия сайта указан IP-адрес");
  if (host.includes("xn--")) add(3, "в адресе похожие символы других алфавитов (punycode)");
  if (u.username || u.password) add(3, "в ссылке есть логин или пароль (приём для маскировки адреса)");
  if (u.protocol === "http:") add(1, "нет шифрования HTTPS");
  if (labels.length >= 5) add(1, "слишком много поддоменов");
  if (host.length > 40) add(1, "очень длинное имя сайта");
  if ((host.match(/-/g) || []).length >= 3) add(1, "много дефисов в имени сайта");
  if (SHORTENERS.has(host)) add(1, "сокращённая ссылка: конечный сайт скрыт");
  if (SUSP_TLD.has(tld)) add(1, `зона .${tld} часто используется мошенниками`);

  const hay = (host + u.pathname).toLowerCase();
  const hits = WORDS.filter((w) => hay.includes(w));
  if (hits.length) add(Math.min(2, hits.length), `слова-приманки в адресе: ${hits.slice(0, 3).join(", ")}`);

  for (const b of BRANDS) {
    if (sld === b) continue;
    const inLabels = labels.some((l) => l !== sld && look(l).includes(b)) || look(sld).includes(b);
    const close = b.length >= 5 && lev(look(sld), b) <= 1;
    if (inLabels || close) { add(3, `имитирует бренд «${b}» на чужом домене`); break; }
  }
  return { ok: true, host, reg, score, reasons };
}

function extractUrl(text) {
  const m = String(text).match(/(https?:\/\/[^\s<>"']+)/i);
  if (m) return m[1];
  const d = String(text).match(/\b((?:[a-z0-9-]+\.)+[a-z]{2,}(?:\/\S*)?)/i);
  return d ? "https://" + d[1] : null;
}

function isPrivateIp(ip) {
  if (net.isIPv4(ip)) {
    const [a, b] = ip.split(".").map(Number);
    return a === 0 || a === 10 || a === 127 || a >= 224 || (a === 169 && b === 254) || (a === 172 && b >= 16 && b <= 31) || (a === 192 && b === 168) || (a === 100 && b >= 64 && b <= 127);
  }
  const v = ip.toLowerCase();
  return v === "::1" || v === "::" || v.startsWith("fc") || v.startsWith("fd") || v.startsWith("fe80") || v.startsWith("::ffff:");
}
async function isPublicHost(host, lookup) {
  try {
    if (net.isIP(host)) return !isPrivateIp(host);
    const addrs = await lookup(host, { all: true });
    return addrs.length > 0 && addrs.every((a) => !isPrivateIp(a.address));
  } catch { return false; }
}

export async function checkLink(input, deps = {}) {
  const fetchImpl = deps.fetchImpl ?? fetch;
  const lookup = deps.lookup ?? dns.lookup;
  const url = extractUrl(input);
  if (!url || url.length > 2000) return { error: "Не нашёл ссылку в сообщении. Пришлите адрес целиком, например https://example.com/page" };

  const first = heuristics(url);
  if (!first.ok) return { error: first.reasons[0] };

  let score = first.score;
  const reasons = [...first.reasons];

  // Разворачиваем редиректы, не скачивая страницу. Внутренние адреса не открываем.
  const hops = [];
  let cur = url;
  let finalUrl = url;
  let skipped = null;
  for (let i = 0; i < 5; i++) {
    let host;
    try { host = new URL(cur).hostname; } catch { break; }
    if (!(await isPublicHost(host, lookup))) { skipped = "адрес не найден или ведёт во внутреннюю сеть, проверка пропущена"; break; }
    try {
      const res = await fetchImpl(cur, { redirect: "manual", signal: AbortSignal.timeout(6000), headers: { "User-Agent": "Mozilla/5.0 BakeliteDefence-LinkCheck" } });
      Promise.resolve(res.body?.cancel?.()).catch(() => {});
      const loc = res.headers.get("location");
      hops.push({ url: cur, status: res.status });
      finalUrl = cur;
      if (res.status >= 300 && res.status < 400 && loc) { cur = new URL(loc, cur).toString(); continue; }
      break;
    } catch { skipped = "сайт не ответил за 6 секунд"; break; }
  }
  if (hops.length >= 4) { score += 1; reasons.push("длинная цепочка переадресаций"); }

  let host = first.host, reg = first.reg;
  if (finalUrl !== url) {
    const fin = heuristics(finalUrl);
    if (fin.ok) {
      host = fin.host; reg = fin.reg;
      if (fin.reg !== first.reg) { score += 1; reasons.push(`ссылка ведёт на другой сайт: ${defang(fin.host)}`); }
      for (const r of fin.reasons) if (!reasons.includes(r)) reasons.push("конечный адрес: " + r);
      score += fin.score;
    }
  }

  // Возраст домена (RDAP)
  let ageDays = null;
  try {
    if (!net.isIP(host)) {
      const r = await fetchImpl(`https://rdap.org/domain/${reg}`, { signal: AbortSignal.timeout(6000), headers: { Accept: "application/rdap+json" } });
      if (r.ok) {
        const d = await r.json();
        const ev = (d.events ?? []).find((e) => e.eventAction === "registration");
        if (ev?.eventDate) {
          ageDays = Math.floor((Date.now() - new Date(ev.eventDate).getTime()) / 86400000);
          if (ageDays < 7) { score += 4; reasons.push(`домен зарегистрирован всего ${ageDays} дн. назад`); }
          else if (ageDays < 30) { score += 3; reasons.push(`домен совсем новый: ${ageDays} дн.`); }
          else if (ageDays < 90) { score += 1; reasons.push(`домен моложе 3 месяцев: ${ageDays} дн.`); }
        }
      }
    }
  } catch {}

  // VirusTotal (если есть ключ)
  let vt = null;
  if (deps.vtKey) {
    try { vt = await vtLookup(finalUrl, deps.vtKey, fetchImpl, deps.sleep ?? sleep); } catch {}
    if (vt) {
      if (vt.malicious >= 3) { score += 8; reasons.push(`VirusTotal: ${vt.malicious} антивирусов считают ссылку вредоносной`); }
      else if (vt.malicious >= 1 || vt.suspicious >= 2) { score += 3; reasons.push(`VirusTotal: вредоносных ${vt.malicious}, подозрительных ${vt.suspicious}`); }
    }
  }

  const verdict = score >= 6 ? "high" : score >= 3 ? "mid" : "low";
  return { url, finalUrl, hops, score, reasons, verdict, ageDays, vt, skipped };
}

async function vtLookup(url, key, fetchImpl, sleepFn) {
  const headers = { "x-apikey": key };
  const id = Buffer.from(url).toString("base64url");
  let r = await fetchImpl(`https://www.virustotal.com/api/v3/urls/${id}`, { headers, signal: AbortSignal.timeout(8000) });
  if (r.status === 404) {
    const sub = await fetchImpl("https://www.virustotal.com/api/v3/urls", {
      method: "POST", headers: { ...headers, "Content-Type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({ url }).toString(), signal: AbortSignal.timeout(8000),
    });
    const aid = (await sub.json())?.data?.id;
    if (!aid) return null;
    for (let i = 0; i < 3; i++) {
      await sleepFn(4000);
      const a = await fetchImpl(`https://www.virustotal.com/api/v3/analyses/${aid}`, { headers, signal: AbortSignal.timeout(8000) });
      const j = await a.json();
      if (j?.data?.attributes?.status === "completed") return j.data.attributes.stats;
    }
    return null;
  }
  if (!r.ok) return null;
  return (await r.json())?.data?.attributes?.last_analysis_stats ?? null;
}

